const sizes = ["XS", "S", "M", "L", "XL", "XXL"];

const makeProduct = (
  id,
  name,
  category,
  price,
  originalPrice,
  image,
  rating,
  colors,
  options = {},
) => ({
  id,
  name,
  category,
  price,
  originalPrice,
  discount: Math.round((1 - price / originalPrice) * 100),
  description:
    options.description ||
    `Discover the elegance of our ${name}. Designed with beautiful details and a comfortable fit for your everyday wardrobe.`,
  images: [image, options.image2 || image],
  sizes: options.sizes || sizes,
  colors,
  rating,
  reviews: options.reviews || 35 + id * 3,
  stock: options.stock ?? 20,
  inStock: (options.stock ?? 20) > 0,
  featured: options.featured ?? false,
  isNew: options.isNew ?? false,
  popularity: options.popularity ?? 100 - id,
});

